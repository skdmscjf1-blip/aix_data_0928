# 20. 크롤링할 때 바로 숫자로 바꾸기
# =============================================================================

data = []


for li in lis:

    name = li.find(
        'h3'
    ).get_text(strip=True)


    price = li.find(
        'span',
        {'class': 'price'}
    ).get_text(strip=True)


    # 마지막 '원' 제거
    price = price[:-1]


    # 문자열 → 정수
    price = int(price)


    star = li.find(
        'span',
        {'class': 'star'}
    ).get_text(strip=True)


    # 문자열 → 실수
    star = float(star)


    data.append(
        [
            name,
            price,
            star
        ]
    )


df = pd.DataFrame(
    data,
    columns=[
        '상품명',
        '가격',
        '별점'
    ]
)


print(df)



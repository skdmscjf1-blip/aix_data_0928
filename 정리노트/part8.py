from bs4 import BeautifulSoup

import pandas as pd


html = """
<ul class="product-list">

    <li>
        <h3>노트북</h3>
        <span class="price">1000000원</span>
        <span class="star">4.8</span>
    </li>

    <li>
        <h3>마우스</h3>
        <span class="price">30000원</span>
        <span class="star">4.5</span>
    </li>

    <li>
        <h3>키보드</h3>
        <span class="price">100000원</span>
        <span class="star">4.7</span>
    </li>

</ul>
"""


# HTML 분석

soup = BeautifulSoup(
    html,
    'html.parser'
)


# 큰 영역 찾기

s_ul = soup.find(
    'ul',
    {'class':'product-list'}
)


# 상품 여러 개 찾기

lis = s_ul.find_all('li')


# 데이터를 담을 빈 리스트

data = []


# 상품 하나씩

for li in lis:


    # 상품명

    name = li.find(
        'h3'
    ).get_text(strip=True)


    # 가격

    price = li.find(
        'span',
        {'class':'price'}
    ).get_text(strip=True)


    # 원 제거

    price = price[:-1]


    # 숫자로 변경

    price = int(price)


    # 별점

    star = li.find(
        'span',
        {'class':'star'}
    ).get_text(strip=True)


    # 숫자로 변경

    star = float(star)


    # 한 행 저장

    data.append(
        [
            name,
            price,
            star
        ]
    )


# DataFrame 생성

df = pd.DataFrame(
    data,
    columns=[
        '상품명',
        '가격',
        '별점'
    ]
)


# 출력

print(df)



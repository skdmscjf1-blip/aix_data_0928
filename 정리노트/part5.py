# =============================================================================

# groupby('학교')
#
# → 기준 1개
#
# 학교별


# groupby(['학교', '학년'])
#
# → 기준 2개
#
# 학교별 + 학년별


# =============================================================================
# 16. groupby 결과의 index
# =============================================================================

result = df.groupby('학교')[
    ['국어', '영어', '수학']
].mean()

print(result)


# 결과를 보면
#
# 학교
#
# 가 일반 열이 아니라
# 왼쪽 index에 들어간다.


# 즉
#
# groupby에 사용한 기준은
# 기본적으로 index 쪽으로 들어가는 경우가 많다.


# =============================================================================
# 17. reset_index() 연결
# =============================================================================

# PART 1에서 배운
#
# reset_index()
#
# 를 여기서 사용할 수 있다.


result = df.groupby('학교')[
    ['국어', '영어', '수학']
].mean()


result = result.reset_index()

print(result)


# 이제
#
# 학교
#
# 가 다시 일반 열로 돌아온다.


# =============================================================================
# ★ groupby() + reset_index()
# =============================================================================

# groupby()
#
#       ↓
#
# 학교가 index로 감
#
#
# reset_index()
#
#       ↓
#
# 학교를 다시 일반 열로


# 실제 데이터 분석에서
# 아주 자주 같이 사용한다.


# =============================================================================
# 18. as_index=False
# =============================================================================

# groupby를 할 때부터
#
# "학교를 index로 보내지 마"
#
# 라고 할 수도 있다.


result = df.groupby(
    '학교',
    as_index=False
)[
    ['국어', '영어', '수학']
].mean()

print(result)


# as
# → ~로
#
# index
# → 행 이름표
#
# False
# → 아니다


# as_index=False
#
# 쉽게:
#
# "groupby 기준을 index로 만들지 마."


# =============================================================================
# ★ reset_index() vs as_index=False
# =============================================================================

# 방법 1
#
# 일단 groupby하고
#
# result = df.groupby('학교')[
#     ['국어', '영어', '수학']
# ].mean()
#
# 그다음
#
# result = result.reset_index()


# 방법 2
#
# 처음부터
#
# result = df.groupby(
#     '학교',

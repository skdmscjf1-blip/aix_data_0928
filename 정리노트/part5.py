import pandas as pd


# =============================================================================
# 0. PART 5에서 사용할 연습용 데이터
# =============================================================================

data = {
    '이름': [
        '강나래', '강태원', '김정민', '김혜성',
        '박동현', '박혜정', '송혜교', '윤종신'
    ],

    '학교': [
        '구로고', '구로고', '디지털고', '디지털고',
        '단지고', '단지고', '구로고', '구로고'
    ],

    '학년': [
        1, 2, 1, 2,
        1, 2, 1, 2
    ],

    '국어': [
        90, 40, 80, 40,
        15, 80, 100, 90
    ],

    '영어': [
        85, 35, 75, 60,
        20, 100, 100, 95
    ],

    '수학': [
        100, 50, 70, 70,
        10, 95, 100, 90
    ]
}


df = pd.DataFrame(data)

print(df)


# [실행 결과]
#
#     이름     학교   학년   국어   영어   수학
# 0  강나래    구로고    1    90    85   100
# 1  강태원    구로고    2    40    35    50

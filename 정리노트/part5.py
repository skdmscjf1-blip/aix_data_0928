# 3  김혜성   디지털고    2    40    60    70
# 4  박동현    단지고    1    15    20    10
# 5  박혜정    단지고    2    80   100    95
# 6  송혜교    구로고    1   100   100   100
# 7  윤종신    구로고    2    90    95    90


# =============================================================================
# 1. groupby()란?
# =============================================================================

# group
# → 그룹 / 묶음
#
# by
# → ~을 기준으로
#
#
# groupby
#
# → "~을 기준으로 묶는다."


# 예)
#
# df.groupby('학교')
#
# 뜻:
#
# "학교를 기준으로 같은 학교끼리 묶어라."


# 현재 학교 데이터를 보면
#
# 구로고
# 구로고
# 디지털고
# 디지털고
# 단지고
# 단지고
# 구로고
# 구로고


# groupby('학교')
#
# 를 하면 머릿속에서는 이렇게 생각하면 된다.
#
#
# ┌ 구로고 ─────────────────┐
# │ 강나래                  │
# │ 강태원                  │
# │ 송혜교                  │
# │ 윤종신                  │
# └─────────────────────────┘
#
# ┌ 디지털고 ────────────────┐
# │ 김정민                  │
# │ 김혜성                  │
# └─────────────────────────┘
#
# ┌ 단지고 ─────────────────┐
# │ 박동현                  │
# │ 박혜정                  │
# └─────────────────────────┘


# =============================================================================
# 2. groupby()만 출력하면?
# =============================================================================

school = df.groupby('학교')

print(school)


# 실행하면 학생 데이터가 바로 나오지 않고
#
# <pandas.core.groupby...>
#
# 같은 내용이 나온다.


# 왜?
#
# groupby()는
#
# "묶는 작업"
#
# 까지만 했기 때문이다.


# 즉
#
# df.groupby('학교')
#
# ↓
#
# 학교별로 묶어놓기만 함


# 그래서 그 뒤에
#
# .mean()
# .sum()
# .count()
#
# 같은 계산을 붙여주는 경우가 많다.


# =============================================================================
# 3. 학교별 국어 평균
# =============================================================================

school = df.groupby('학교')['국어'].mean()

print(school)


# [실행 결과]
#
# 학교
# 구로고      80.00
# 단지고      47.50
# 디지털고    60.00
#
# Name: 국어, dtype: float64


# =============================================================================
# 코드 하나씩 아주 쉽게 해석
# =============================================================================

# df
#
# → 전체 학생 데이터


# .groupby('학교')
#
# → 학교가 같은 학생끼리 묶기


# ['국어']
#
# → 그중 국어점수만 선택


# .mean()
#
# → 평균 계산


# 따라서
#
# df.groupby('학교')['국어'].mean()
#
# 전체 뜻:
#
# "학생들을 학교별로 묶고
#  각 학교의 국어점수 평균을 구해라."


# =============================================================================
# 4. 실제 계산 과정을 직접 확인
# =============================================================================

# 구로고 국어점수
#
# 강나래 → 90

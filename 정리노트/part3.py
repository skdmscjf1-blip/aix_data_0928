# =============================================================================
# 28. 조건검색
# =============================================================================

# Pandas에서 매우 중요한 부분
#
# 원하는 조건을 만족하는 행만 가져올 수 있다.


# 예)
#
# 키가 185 이상인 학생


print(df['키'] >= 185)


# 결과는
#
# True
# False
# True
#
# 같은 형태로 나온다.


# True
# → 조건 만족
#
# False
# → 조건 불만족


# =============================================================================
# 29. 조건을 DataFrame에 넣기
# =============================================================================

print(df[df['키'] >= 185])


# 구조를 보면
#
# df[
#
#     df['키'] >= 185
#
# ]


# 안쪽부터 생각한다.


# ①
#
# df['키']
#
# → 키 열 선택


# ②
#
# df['키'] >= 185
#
# → 각각 185 이상인지 검사


# ③
#
# True인 행만
#
# df[조건]
#
# 으로 가져온다.


# 즉
#
# df[df['키'] >= 185]
#
# 뜻:
#
# "df에서 키가 185 이상인 학생만 가져와."


# =============================================================================
# 30. 문자열 조건검색
# =============================================================================

# 학교가 구로고인 학생


print(df[df['학교'] == '구로고'])


# 여기서
#
# ==
#
# → 같다


# 주의
#
# =
#
# → 값을 저장


# ==
#
# → 같은지 비교


# 예)
#
# x = 10
#
# → x에 10 저장


# x == 10
#
# → x가 10과 같은지 확인


# =============================================================================
# 31. 여러 조건 - &
# =============================================================================

# &
#
# and
#
# → 그리고
#
# 두 조건을 모두 만족해야 한다.


# 예)
#
# 키가 185 이상
#
# 그리고
#
# 학교가 구로고


result = df[
    (df['키'] >= 185) &
    (df['학교'] == '구로고')
]

print(result)


# 중요
#
# 각각의 조건을
#
# ()
#
# 괄호로 감싸준다.


# 구조
#
# (조건1) & (조건2)


# =============================================================================
# 32. 여러 조건 - |
# =============================================================================

# |
#
# or
#
# → 또는
#
# 둘 중 하나라도 만족하면 선택


# 예)
#
# 학교가 구로고
#
# 또는
#
# 학교가 단지고


result = df[
    (df['학교'] == '구로고') |
    (df['학교'] == '단지고')
]

print(result)


# =============================================================================
# 33. ~
# =============================================================================

# ~
#
# not
#
# → 반대


# 예)
#
# 구로고가 아닌 학생


result = df[
    ~(df['학교'] == '구로고')
]

print(result)


# 쉽게
#
# df['학교'] == '구로고'
#
# → 구로고인가?
#
#
# ~
#
# → 그 결과를 반대로


# 따라서
#
# 구로고가 아닌 학생


# =============================================================================
# ★ & vs | vs ~
# =============================================================================

# &
# → 그리고
#
# 조건1과 조건2를 모두 만족


# |
# → 또는
#
# 조건1 또는 조건2 중 하나 이상 만족


# ~
# → 반대
#
# 조건이 아닌 데이터


# =============================================================================
# 34. sort_values()
# =============================================================================

# sort
# → 정렬하다
#
# values
# → 값들
#
# sort_values()
#
# → 특정 열의 값을 기준으로 정렬


print(df.sort_values('국어'))


# 기본은
#
# 작은 값
# ↓
# 큰 값
#
# 순서


# 이것을
#
# 오름차순
#
# 이라고 한다.


# =============================================================================
# 35. ascending=
# =============================================================================

# ascending
#
# ascend = 올라가다
#
# ascending
# → 올라가는


# ascending=True
#
# → 오름차순
#
# 작은 값 → 큰 값


print(
    df.sort_values(
        '국어',
        ascending=True
    )
)


# =============================================================================
# 36. 내림차순
# =============================================================================

# ascending=False
#
# → 올라가는 것이 아니다
#
# → 내림차순


print(
    df.sort_values(
        '국어',
        ascending=False
    )
)


# 결과
#
# 높은 국어점수
# ↓
# 낮은 국어점수


# =============================================================================
# 37. 여러 열을 기준으로 정렬
# =============================================================================

result = df.sort_values(
    ['학교', '국어']
)

print(result)


# 뜻
#
# ① 학교를 기준으로 정렬
#
# ② 같은 학교 안에서는 국어점수로 정렬


# =============================================================================
# 38. 열마다 정렬 방향 다르게 지정
# =============================================================================

result = df.sort_values(
    ['학교', '국어'],
    ascending=[True, False]
)

print(result)


# 해석
#
# ['학교', '국어']
#
#       ↓       ↓
#
#     True    False
#
#
# 학교
# → 오름차순
#
# 국어
# → 내림차순


# 즉 같은 학교 안에서는
#
# 국어점수가 높은 학생부터 보여준다.



# 2. Series
# =============================================================================

# Series = 연속된 자료
#
# Pandas에서는
#
# → 1차원 데이터
#
# 처음에는 쉽게
#
# "한 줄짜리 데이터"
#
# 라고 생각하면 된다.


# 사용방법
#
# pd.Series([데이터])


# 예)
#
# scores = pd.Series([90, 80, 100, 70])


# 출력하면
#
# 0     90
# 1     80
# 2    100
# 3     70


# 왼쪽
#
# 0
# 1
# 2
# 3
#
# → index


# 오른쪽
#
# 90
# 80
# 100
# 70
#
# → value


# 따라서 Series의 기본 구조
#
# index + value


# =============================================================================
# 3. index란?
# =============================================================================

# index = 색인 / 찾아보기 위한 표시
#
# 영어 뜻만 보면 어려울 수 있다.
#
# 처음에는
#
# "각 행에 붙어있는 이름표"
#
# 라고 생각하면 된다.


# 예)
#
# index     점수
#
#   0        90
#   1        80
#   2       100
#   3        70


# 여기서
#
# 0, 1, 2, 3
#
# → 각각의 데이터를 찾기 위한 이름표


# =============================================================================
# 4. Series의 index 직접 지정
# =============================================================================

# index는 숫자만 사용할 필요가 없다.
#
# 우리가 직접 이름을 지정할 수도 있다.


# 예)
#
# scores = pd.Series(
#     [90, 80, 100],
#     index=['홍길동', '유관순', '이순신']
# )


# 결과
#
# 홍길동     90
# 유관순     80
# 이순신    100


# 이제 데이터를 이름으로 찾을 수 있다.
#
# scores['홍길동']


# 결과
#
# 90


# 즉
#
# 홍길동이라는 index를 찾아서
# 그 옆에 있는 값 90을 가져온다.


# =============================================================================
# 5. DataFrame
# =============================================================================

# DataFrame
#
# Data = 데이터
# Frame = 틀
#
# 즉
#
# "데이터를 담는 표"


# Excel의 표와 비슷하게 생각하면 된다.


# Series
# → 한 줄짜리 데이터


# DataFrame
# → 여러 행 + 여러 열로 이루어진 표


# 예)
#
# data = {
#     '이름':['홍길동','유관순','이순신'],
#     '국어':[90,80,100],
#     '영어':[80,90,85]
# }
#
# df = pd.DataFrame(data)


# 결과
#
#       이름    국어    영어
# 0    홍길동    90     80
# 1    유관순    80     90
# 2    이순신   100     85


# =============================================================================
# 6. DataFrame의 구조
# =============================================================================

#             columns
#                ↓
#
#        이름    국어    영어
#
# 0     홍길동    90     80
# 1     유관순    80     90
# 2     이순신   100     85
#
# ↑
# index


# 쉽게
#
# index
# → 행의 이름표
#
# columns
# → 열의 이름
#
# values
# → 안에 들어있는 실제 값


# =============================================================================
# 7. Series와 DataFrame의 차이
# =============================================================================

# 매우 중요!


# -----------------------------------------------------------------------------
# [1] 열 하나 가져오기
# -----------------------------------------------------------------------------

# df['국어']


# 결과
#
# 0     90
# 1     80
# 2    100


# 이것은
#
# Series


# 왜?
#
# → 국어라는 한 열만 가져왔기 때문


# -----------------------------------------------------------------------------
# [2] 대괄호를 한 번 더 사용
# -----------------------------------------------------------------------------

# df[['국어']]


# 결과
#
#      국어
# 0     90
# 1     80
# 2    100


# 이것은
#
# DataFrame


# -----------------------------------------------------------------------------
# [3] 여러 열 선택
# -----------------------------------------------------------------------------

# df[['국어', '영어']]


# 결과
#
#      국어   영어
# 0     90    80
# 1     80    90
# 2    100    85


# 이것도
#
# DataFrame


# -----------------------------------------------------------------------------
# ★ 핵심 비교
# -----------------------------------------------------------------------------

# df['국어']
#
# → Series


# df[['국어']]
#
# → DataFrame


# df[['국어', '영어']]
#
# → DataFrame


# =============================================================================
# 8. columns
# =============================================================================

# column = 열
# columns = 열들


# df.columns



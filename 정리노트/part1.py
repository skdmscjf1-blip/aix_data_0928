# 9. index
# =============================================================================

# df.index


# → DataFrame의 index 확인


# 처음 DataFrame을 만들면 보통
#
# 0
# 1
# 2
#
# 같은 숫자 index가 자동으로 만들어진다.


# 예)
#
#       이름
# 0    홍길동
# 1    유관순
# 2    이순신
#
# ↑
#
# 0, 1, 2가 index


# =============================================================================
# 10. set_index()
# =============================================================================

# set = 설정하다
# index = 행 이름표


# set_index()
#
# → 특정 열을 index로 설정


# 예)
#
# df.set_index('이름')


# 실행 전
#
#       이름    국어   영어
# 0    홍길동    90    80
# 1    유관순    80    90
# 2    이순신   100    85


# 실행 후
#
#           국어   영어
# 이름
# 홍길동      90    80
# 유관순      80    90
# 이순신     100    85


# 무엇이 바뀌었을까?
#
# '이름'이 일반 열에서 빠져나와
#
# ↓
#
# index 자리로 이동했다.


# =============================================================================
# 11. set_index()를 사용하는 이유
# =============================================================================

# 기존 상태
#
#       이름
# 0    홍길동
# 1    유관순
# 2    이순신


# 여기서는
#
# 0
# 1
# 2
#
# 가 index이다.


# 그런데
#
# df.set_index('이름')
#
# 을 사용하면


# index가
#
# 홍길동
# 유관순
# 이순신
#
# 으로 변경된다.


# 그러면
#
# df.loc['이순신']
#
# 처럼 이름을 이용해서 데이터를 찾을 수 있다.


# 쉽게 말하면
#
# set_index()
#
# → "내가 데이터를 찾기 편한 열을
#     행의 이름표로 바꾸는 것"


# =============================================================================
# 12. inplace=True
# =============================================================================

# inplace
#
# in = 안에서
# place = 자리


# in place
#
# → 그 자리에서


# Pandas에서는
#
# "원본 자체를 변경해라"
#
# 라고 이해하면 된다.


# -----------------------------------------------------------------------------
# inplace=True가 없는 경우
# -----------------------------------------------------------------------------

# df.set_index('이름')


# → 변경된 결과가 만들어짐
#
# 하지만 원본 df 자체는
# 그대로 있을 수 있다.


# -----------------------------------------------------------------------------
# inplace=True 사용
# -----------------------------------------------------------------------------

# df.set_index('이름', inplace=True)


# → 원본 df 자체를 변경


# 따라서 다시
#
# df
#
# 를 출력해도
#
# 이름이 index로 변경된 상태가 유지된다.


# -----------------------------------------------------------------------------
# ★ 쉽게 비교
# -----------------------------------------------------------------------------

# inplace=False
#
# → 변경 결과만 만들어줌
#
# → 원본은 그대로


# inplace=True
#
# → 원본 자체를 변경


# =============================================================================
# 13. reset_index()
# =============================================================================

# reset = 초기 상태로 되돌리다
# index = 행 이름표


# reset_index()
#
# → 현재 index를 다시 일반 열로 돌려놓는다.


# 현재
#
#           국어
# 이름
# 홍길동      90
# 유관순      80
# 이순신     100


# 실행
#
# df.reset_index()


# 결과
#
#       이름    국어
# 0    홍길동    90
# 1    유관순    80
# 2    이순신   100


# 즉
#
# 이름
# ↓
# 다시 일반 열


# 그리고
#
# 0
# 1
# 2
#
# ↓
# 다시 기본 index


# =============================================================================
# 14. set_index()와 reset_index() 비교
# =============================================================================

# set_index()
#
# 일반 열
#    ↓
# index


# reset_index()
#
# index
#    ↓
# 일반 열


# 쉽게 그림으로 보면
#
#
#        set_index('이름')
#
# 이름 열  ───────────────→ index
#
#
#        reset_index()
#
# index   ───────────────→ 일반 열



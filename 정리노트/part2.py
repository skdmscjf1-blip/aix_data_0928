# 여기서 index를 보면
#
# 0
# 1
# 0
# 1
#
# 로 되어 있다.


# 왜?
#
# df1의 기존 index
#
# 0
# 1
#
# +
#
# df2의 기존 index
#
# 0
# 1
#
# 를 그대로 합쳤기 때문이다.


# =============================================================================
# 16. ignore_index=True
# =============================================================================

# ignore = 무시하다

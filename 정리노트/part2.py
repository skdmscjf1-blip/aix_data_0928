# =============================================================================
# ⭐ PART 2 헷갈리는 것 최종 비교
# =============================================================================


# -----------------------------------------------------------------------------
# ① read_csv() vs read_excel()
# -----------------------------------------------------------------------------

# read_csv()
# → CSV / 구분자로 나뉜 텍스트 데이터 읽기
#
# read_excel()
# → Excel 파일 읽기


# -----------------------------------------------------------------------------
# ② sep vs encoding
# -----------------------------------------------------------------------------

# sep
# → 어디서 데이터를 나눌까?
#
# encoding
# → 글자를 어떤 방식으로 읽을까?


# -----------------------------------------------------------------------------
# ③ skiprows vs nrows
# -----------------------------------------------------------------------------

# skiprows
# → 몇 행을 건너뛸까?
#
# nrows
# → 몇 행을 읽을까?


# -----------------------------------------------------------------------------
# ④ usecols vs index_col
# -----------------------------------------------------------------------------

# usecols
# → 어떤 열을 가져올까?
#
# index_col
# → 어떤 열을 index로 사용할까?


# -----------------------------------------------------------------------------
# ⑤ set_index() vs index_col
# -----------------------------------------------------------------------------

# index_col
# → 파일을 읽을 때 바로 index 설정
#
# set_index()
# → DataFrame을 만든 후 index 변경


# -----------------------------------------------------------------------------
# ⑥ to_csv() vs to_excel()
# -----------------------------------------------------------------------------

# to_csv()
# → CSV로 저장
#
# to_excel()
# → Excel로 저장


# -----------------------------------------------------------------------------
# ⑦ concat axis=0 vs axis=1
# -----------------------------------------------------------------------------

# axis=0
# → 위 / 아래로 합침
# → 행 증가
#
#
# axis=1
# → 왼쪽 / 오른쪽으로 합침
# → 열 증가



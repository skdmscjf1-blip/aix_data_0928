#
# ignore_index=True
#
# → 기존 index를 무시하고
#   새로운 index를 만들어라.


result = pd.concat(
    [df1, df2],
    ignore_index=True
)

print(result)


# 실행 결과
#
#      이름   국어
# 0   홍길동   90
# 1   유관순   80
# 2   이순신  100
# 3   강감찬   95


# 기존
#
# 0 1 + 0 1
#
# 이 아니라
#
# 0
# 1
# 2
# 3

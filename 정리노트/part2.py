# -----------------------------------------------------------------------------
# [실제 실행 예제]
# -----------------------------------------------------------------------------

df1 = pd.DataFrame({
    '이름': ['홍길동', '유관순'],
    '국어': [90, 80]
})

df2 = pd.DataFrame({
    '이름': ['이순신', '강감찬'],
    '국어': [100, 95]
})


print(df1)
print(df2)


# =============================================================================
# 15. concat() 세로로 합치기
# =============================================================================

result = pd.concat([df1, df2])

print(result)


# 실행 결과
#
#      이름   국어
# 0   홍길동   90
# 1   유관순   80
# 0   이순신  100

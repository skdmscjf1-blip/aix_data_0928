# =============================================================================
# 18. axis=0 실제 실행
# =============================================================================

df_a = pd.DataFrame({
    '이름': ['홍길동', '유관순'],
    '점수': [90, 80]
})

df_b = pd.DataFrame({
    '이름': ['이순신', '강감찬'],
    '점수': [100, 95]
})


result_axis0 = pd.concat(
    [df_a, df_b],
    axis=0,
    ignore_index=True
)

print(result_axis0)


# 실행 결과
#
#      이름   점수
# 0   홍길동   90
# 1   유관순   80
# 2   이순신  100
# 3   강감찬   95


# 즉
#
# df_a
# ↓
# df_b
#
# 위아래로 연결


# =============================================================================
# 19. axis=1 실제 실행
# =============================================================================

df_name = pd.DataFrame({
    '이름': ['홍길동', '유관순']
})

df_score = pd.DataFrame({
    '국어': [90, 80],
    '영어': [80, 90]
})


result_axis1 = pd.concat(
    [df_name, df_score],
    axis=1
)

print(result_axis1)


# 실행 결과
#
#      이름   국어   영어
# 0   홍길동   90    80
# 1   유관순   80    90


# 즉
#
# df_name + df_score
#
# 왼쪽 / 오른쪽으로 연결


# =============================================================================
# ★ axis=0 vs axis=1
# =============================================================================

# axis=0
#
# DataFrame
#     ↓
# DataFrame
#
# → 위 / 아래
# → 행이 늘어남
#
# 쉽게
#
# "세로로 길어진다."


# axis=1
#
# DataFrame + DataFrame
#
# → 왼쪽 / 오른쪽
# → 열이 늘어남
#
# 쉽게
#
# "가로로 넓어진다."



def change_lang(lang):

    # lang에 값이 있다면
    if pd.notnull(lang):

        # 양쪽 공백을 제거하고
        # 소문자로 변경
        return lang.strip().lower()

    # 값이 없다면
    return '없음'


df2 = df.copy()

df2['SW특기'] = df2['SW특기'].apply(change_lang)

print(df2[['이름', 'SW특기']])


